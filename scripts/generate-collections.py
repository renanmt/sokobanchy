#!/usr/bin/env python3
"""Extract credited boards without changing them; retain original source notices.

Only the reviewed .sok allowlist in catalog.json is read, never shared/ or images.
Source bytes, including all commentaries and solutions, ship unchanged.
"""
import hashlib
import json
from pathlib import Path
import runpy

ROOT = Path(__file__).resolve().parent.parent
DEST = ROOT / 'assets/collections'
api = runpy.run_path(str(ROOT / 'scripts/analyze-levels.py'))
catalog = json.loads((DEST / 'catalog.json').read_text())
entries = []
witnesses = {}
for entry in catalog:
    stem = entry['id']
    source = DEST / 'sources' / (stem + '.sok')
    raw = source.read_bytes()
    assert hashlib.sha256(raw).hexdigest() == entry['source_sha256'], source
    try:
        text = raw.decode('utf-8-sig')
    except UnicodeDecodeError:
        text = raw.decode('cp1252')
    lines = text.splitlines()
    levels = api['parse_file'](source)
    boards = []
    board_lines = set()
    solutions = []
    for level in levels:
        start = level['line'] - 1
        rows = lines[start:start + level['height']]
        board_lines.update(range(start, start + level['height']))
        boards.append('; ' + level['name'] + '\n' + '\n'.join(rows))
        solution = next((s for s in level['solutions'] if api['replay'](level, s)), None)
        assert solution is not None, (stem, level['name'])
        solutions.append(solution)
    (DEST / (stem + '.xsb')).write_text('\n\n'.join(boards) + '\n')
    # Preserve all prose, authorship, copyright, and commentaries for the About page.
    # The unchanged originals retain boards, recordings, and file-format comments too.
    notes = [s for i, s in enumerate(lines) if i not in board_lines
             and not s.startswith('::') and not (s.strip() and set(s.strip()) <= set('udlrUDLR'))]
    (DEST / (stem + '.txt')).write_text('\n'.join(notes).strip() + '\n')
    witnesses[stem] = solutions
    q = lambda s: json.dumps(s, ensure_ascii=False)
    entries.append(
        '    Collection {\n'
        f'        id: {q(stem)},\n        name: {q(entry["name"])},\n'
        f'        author: {q(entry["author"])},\n        website: {q(entry["website"])},\n'
        f'        count: {len(levels)},\n'
        f'        boards: include_str!("../assets/collections/{stem}.xsb"),\n'
        f'        notes: include_str!("../assets/collections/{stem}.txt"),\n'
        '    },\n'
    )
    print(f'{entry["name"]}: {len(levels)} unchanged boards, solutions verified')
(ROOT / 'src/collections.rs').write_text(
    '// Generated by scripts/generate-collections.py.\n'
    'pub struct Collection {\n'
    '    pub id: &\'static str,\n    pub name: &\'static str,\n'
    '    pub author: &\'static str,\n    pub website: &\'static str,\n'
    '    pub count: usize,\n    pub boards: &\'static str,\n    pub notes: &\'static str,\n'
    '}\n\npub const COLLECTIONS: &[Collection] = &[\n' + ''.join(entries) + '];\n'
)
(ROOT / 'tests/collection-solutions.json').write_text(json.dumps(witnesses, indent=2) + '\n')
