#!/usr/bin/env python3
"""Rebuild the curated original campaign and witnesses from its source metadata.

Selection is deliberate: do not replace these boards with a random sample.
Use `cargo run --release --example campaign_lab -- verify assets/levels.xsb`
to independently solve them again and prove their minimum push counts.
"""
import json
from pathlib import Path

root = Path(__file__).resolve().parent.parent
campaign = json.loads((root / 'assets/campaign.json').read_text())
levels = campaign['levels']
assert len(levels) == 35
assert len({tuple(level['rows']) for level in levels}) == len(levels)
assert len({level['name'] for level in levels}) == len(levels)
assert [(level['pushes'], level['overhead']) for level in levels] == sorted(
    (level['pushes'], level['overhead']) for level in levels
)
assert all(set(level['solution'].lower()) <= set('udlr') for level in levels)
chapters = [levels[i]['chapter'] for i in range(0, len(levels), 5)]
assert len(chapters) == len(set(chapters))
assert all(level['chapter'] == chapters[i // 5] for i, level in enumerate(levels))
(root / 'src/campaign.rs').write_text(
    '// Generated by scripts/generate-levels.py from assets/campaign.json.\n'
    f'pub const NAME: &str = {json.dumps(campaign["name"])};\n'
    f'pub const LEVEL_COUNT: usize = {len(levels)};\n'
    'pub const CHAPTER_SIZE: usize = 5;\n'
    f'pub const CHAPTERS: [&str; {len(chapters)}] = [\n'
    + ''.join(f'    {json.dumps(chapter)},\n' for chapter in chapters)
    + '];\n'
)
(root / 'assets/levels.xsb').write_text('\n\n'.join(
    '; ' + level['name'] + '\n' + '\n'.join(level['rows']) for level in levels
) + '\n')
(root / 'tests/solutions.json').write_text(json.dumps(
    [level['solution'] for level in levels], indent=2
) + '\n')
print(f"Rebuilt {len(levels)} original campaign puzzles and their verified solutions")
